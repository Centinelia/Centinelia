/**
 * Runs a single round-trip comparison between a real CFDI XML from CONTPAQi
 * and the XML our adapter would have generated for the same transaction.
 *
 * @param originalXmlPath  Absolute or relative path to the real CFDI XML from CONTPAQi.
 * @param adapterInputPath Absolute or relative path to the adapter input JSON
 *                         ({ invoice: BillingInvoice, config: XmlImportConfig }).
 * @returns DiffReport with structured diffs and a human-readable summary.
 */
export function runRoundTrip(originalXmlPath: string, adapterInputPath: string): DiffReport {
  const fixture = path.basename(adapterInputPath, '.input.json');

  const originalXml = fs.readFileSync(originalXmlPath, 'utf8');
  const adapterInputRaw = fs.readFileSync(adapterInputPath, 'utf8');
  const adapterInput = JSON.parse(adapterInputRaw) as AdapterInput;

  // Build our XML
  const ourXml = buildImportXml([adapterInput.invoice], adapterInput.config);

  // Parse both sides
  const cfdi = parseCfdiXml(originalXml);
  const ours = parseOurXml(ourXml);

  // Compare
  const diffs: FieldDiff[] = [
    ...compareEncabezado(ours.encabezado, cfdi.encabezado),
    ...compareMovimientos(ours.movimientos, cfdi.movimientos),
  ];

  const passed = diffs.length === 0;
  const summary = passed
    ? `PASS — ${fixture}: all ${Object.keys(ours.encabezado).length + ours.movimientos.length * 5} comparable fields match`
    : `FAIL — ${fixture}: ${diffs.length} diff(s) found`;

  return {
    fixture,
    passed,
    diffs,
    ignoredFields: Array.from(IGNORED_FIELDS),
    summary,
  };
}

/**
 * Formats a DiffReport as a human-readable string for console output.
 */
export function formatDiffReport(report: DiffReport): string {
  const lines: string[] = [`=== Round-Trip Report: ${report.fixture} ===`, report.summary, ''];

  if (report.passed) {
    lines.push('All comparable fields match.');
  } else {
    lines.push('DIFFS:');
    for (const diff of report.diffs) {
      const label =
        diff.status === 'mismatch'
          ? 'MISMATCH'
          : diff.status === 'missing_in_ours'
            ? 'MISSING IN OURS'
            : 'EXTRA IN OURS';
      lines.push(`  [${label}] ${diff.field}`);
      lines.push(`    Ours  : ${diff.ourValue ?? '(absent)'}`);
      lines.push(`    Theirs: ${diff.theirValue ?? '(absent)'}`);
    }
  }

  lines.push('');
  lines.push(`Ignored fields (${report.ignoredFields.length}): ${report.ignoredFields.join(', ')}`);

  return lines.join('\n');
}
